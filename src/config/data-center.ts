import type { ArticleBlock } from "@/config/articles";

/**
 * B2B section at /data-center — equipment supply for data-center projects
 * (electroustanovok, EPC/electrical contractors, system integrators, design
 * institutes, industrial customers, procurement/tender departments).
 *
 * Categories are config-driven, not DB Category rows — unlike the main
 * catalog taxonomy, several subcategories below (UPS, precision cooling,
 * server racks, generators, fire suppression) have no real AIMAG stock
 * behind them yet. Modeling them as real Category/Product rows would
 * fabricate a catalog that doesn't exist; modeling them here as an RFQ-only
 * sourcing page is honest about what AIMAG actually offers today: direct
 * stock for the items that overlap its real catalog (linked via
 * relatedCategorySlug, a slug from the real src/config/category-seo.ts
 * taxonomy), and sourced-to-order supply for everything else — true to
 * "Подбор аналогов" / "Поставка оборудования под проект" in the brief,
 * not an inventory claim.
 */

export interface DataCenterSubcategory {
  label: string;
  /** Real catalog Category.slug to cross-link, when AIMAG genuinely stocks this — omitted (RFQ-only) when it doesn't. */
  relatedCategorySlug?: string;
}

