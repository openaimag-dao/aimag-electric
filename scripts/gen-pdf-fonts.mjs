// One-off generator → prints TS for src/lib/pdf/fonts-base64.ts
// Embeds the Roboto woff files as base64 so the PDF renderer never needs
// filesystem access to fonts at request time (see render-pdf.ts).
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src/lib/pdf/fonts");

const regular = readFileSync(path.join(dir, "Roboto-Regular.woff")).toString("base64");
const bold = readFileSync(path.join(dir, "Roboto-Bold.woff")).toString("base64");

console.log(`// AUTO-GENERATED by scripts/gen-pdf-fonts.mjs — do not edit by hand.
// Base64 of src/lib/pdf/fonts/*.woff, embedded so render-pdf.ts never needs
// filesystem access to fonts at request time.
export const ROBOTO_REGULAR_BASE64 = "${regular}";
export const ROBOTO_BOLD_BASE64 = "${bold}";
`);
